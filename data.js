<li><b>유성생식</b>: 반수체(n) 배우자 2개 융합 → 이배체(2n) 접합자. 각 부모 유전자의 절반만 전달. <mark>가장 큰 장점 = 유전자 재조합 → 유전적 다양성 → 환경 변화에 잘 적응</mark></li>
